const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, filename)
const { crossCheck, dummyEvidence, validateEvidence } = require('../lib/evidence.ts')
const { createReview, transition, saveEvidence, owner, roles } = require('../lib/review.ts')
const evidence = dummyEvidence()
let report = crossCheck('all', evidence)
assert.equal(report.included, 6)
assert.equal(report.screened, 4)
assert.equal(report.findings.filter(f => f.kind === 'Unscreened security').length, 2)
assert.equal(report.findings.filter(f => f.kind === 'Failed exclusion').length, 1)
assert.deepEqual(report.findings.find(f => f.kind === 'Failed exclusion').evidenceIds, ['BBG-5', 'MSCI-5'])
assert.equal(crossCheck('qualified', evidence).findings.length, 1)
assert.equal(crossCheck('all', []).blockers.length, 1)
assert.equal(crossCheck('qualified', evidence.filter(r => r.source === 'Internal')).blockers.length, 1)
const corrected = evidence.map(r => r.id === 'BBG-5' ? { ...r, included: false, note: 'Simulated supported index update: exclude failed bond.' } : r)
assert.equal(crossCheck('qualified', corrected).findings.length, 0)
assert.equal(crossCheck('all', corrected).findings.length, 2)
assert.equal(crossCheck('qualified', corrected).triggers.length, 1)
assert.equal(crossCheck('qualified', evidence.map(r => r.id === 'MSCI-5' ? {...r, applicable: false} : r)).findings.length, 0)
assert.equal(crossCheck('qualified', evidence.map(r => r.id === 'MSCI-5' ? {...r, result: 'passed'} : r)).findings.length, 0)
assert.ok(validateEvidence([...evidence, {...evidence[0], id: 'OTHER'}]))
const allPassed = evidence.filter(r => r.source === 'Bloomberg' || r.source === 'Internal').concat(evidence.filter(r => r.source === 'Bloomberg').map((r,i) => ({ ...r, source: 'MSCI', id: `NEW-${i}`, result: 'passed' })))
assert.equal(crossCheck('all', allPassed).findings.length, 0)
for (const material of [false, true]) {
 let r = createReview('TEST', 'routine', 'all')
 const step = action => {
  const role = owner(r)
  for (const other of roles.filter(v => v !== role)) assert.equal(transition(r, action, other), r)
  const next = transition(r, action, role)
  assert.notEqual(next, r, action)
  r = next
 }
 assert.equal(transition(r, 'evidence', 'Disclosure Team'), r)
 assert.equal(saveEvidence(r, evidence, 'Product Management'), r)
 r = saveEvidence(r, evidence, 'Disclosure Team')
 step('evidence'); step('verify')
 const originalSnapshot = r.events.at(-1).report.snapshot
 step('technical'); step(material ? 'material' : 'nonmaterial')
 if (material) { assert.equal(transition(r, 'correct', 'Product Management'), r); step('risk') }
 r = saveEvidence(r, corrected, 'Disclosure Team')
 assert.equal(r.result, null)
 assert.equal(originalSnapshot.find(v => v.id === 'BBG-5').included, true)
 step('correct'); step('verify'); step('technical')
 if (material) { assert.equal(r.stage, 'closure'); assert.equal(transition(r, 'approve', 'Product Management'), r); step('close') }
 step('approve')
 assert.equal(r.stage, 'approved')
 assert.equal(r.target, 'proposed')
 assert.equal(saveEvidence(r, evidence, 'Disclosure Team'), r)
}
console.log('PASS: evidence-dependent checks, source linking, independent failed exclusions, notes-only triggers, empty-scope blocking, duplicate validation, role guards, both correction paths, approval gates and immutable snapshots.')
